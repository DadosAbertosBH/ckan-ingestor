import { expect, test } from '@playwright/test';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';

test('native DuckLake catalog, remote range reads, visual exploration and SQL', async ({ page }) => {
  const fixtures = path.resolve('e2e/fixtures');
  const publication = JSON.parse(await readFile(path.join(fixtures, 'manifest.json'), 'utf8'));
  const reads: string[] = [];
  const scopes: string[][] = [];
  await page.route('**/api/session', route => {
    const input = route.request().postDataJSON() ?? {};
    scopes.push(input.tables ?? []);
    return route.fulfill({ json: { publication, files: publication.fixtureFiles, endpoint: 'https://r2.test', credentials: { accessKeyId: 'temporary-key', secretAccessKey: 'temporary-secret', sessionToken: 'session' }, expiresAt: Date.now() + 900_000 } });
  });
  await page.route('**/api/latest', route => route.fulfill({ json: { id: publication.id, createdAt: publication.createdAt } }));
  await page.route('https://r2.test/**', async route => {
    const request = route.request();
    expect(request.headers()['x-amz-security-token']).toBe('session');
    const key = decodeURIComponent(new URL(request.url()).pathname).replace('/fixture/', '');
    const file = path.join(fixtures, key);
    const { size } = await stat(file);
    const headers: Record<string, string> = { 'Content-Length': String(size), 'Accept-Ranges': 'bytes', 'Access-Control-Allow-Origin': '*', 'Access-Control-Expose-Headers': 'Content-Range,Content-Length,Accept-Ranges', 'Content-Type': 'application/octet-stream' };
    if (request.method() === 'HEAD') return route.fulfill({ status: request.headers()['range'] ? 206 : 200, headers });
    const body = await readFile(file);
    const range = request.headers()['range'];
    if (range) {
      reads.push(key);
      const [, first, last] = /bytes=(\d+)-(\d*)/.exec(range)!;
      const start = Number(first), end = last ? Math.min(Number(last), size - 1) : size - 1;
      headers['Content-Range'] = `bytes ${start}-${end}/${size}`;
      headers['Content-Length'] = String(end - start + 1);
      return route.fulfill({ status: 206, headers, body: body.subarray(start, end + 1) });
    }
    return route.fulfill({ status: 200, headers, body });
  });
  page.on('console', msg => { if (msg.type() === 'error') console.log(msg.text()); });
  page.on('pageerror', error => console.log('PAGE ERROR', error.message));
  await page.goto('/');
  await page.getByRole('button', { name: /^Explorar dados/ }).click();
  await expect.poll(async () => await page.getByRole('alert').count() ? await page.getByRole('alert').textContent() : await page.getByRole('button', { name: /despesas/ }).count() ? 'ready' : 'loading', { timeout: 60000 }).toBe('ready');
  await page.getByLabel('Fonte', { exact: true }).selectOption('fixture-source');
  await page.getByRole('button', { name: /Finanças municipais/ }).click();
  await page.getByLabel('Mostrar todos os recursos').check();
  await page.getByRole('button', { name: /Empenhos em preparação/ }).click();
  await expect(page.getByRole('heading', { name: 'Empenhos em preparação' })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('Aguardando ingestão');
  await page.getByRole('button', { name: /despesas/ }).click();
  await expect(page.getByRole('cell', { name: 'São Paulo', exact: true }).first()).toBeVisible();
  await page.getByLabel('Valor do filtro').fill('Recife');
  await page.getByLabel('Coluna do filtro').selectOption('cidade');
  await page.getByRole('button', { name: 'Aplicar filtro' }).click();
  await expect(page.getByRole('cell', { name: 'Recife', exact: true }).first()).toBeVisible();
  await expect(page.getByRole('cell', { name: 'São Paulo', exact: true })).toHaveCount(0);
  const filteredDownload = page.waitForEvent('download', { timeout: 10000 });
  await page.getByRole('button', { name: '↓ CSV', exact: true }).click();
  expect(await readFile((await (await filteredDownload).path())!, 'utf8')).toContain('Recife');
  await page.getByRole('tab', { name: 'SQL', exact: true }).click();
  await expect(page.locator('.cm-editor')).toBeVisible();
  await page.getByLabel('Consulta SQL').fill('SELECT count(*) AS total FROM lake.main.despesas');
  await page.getByRole('button', { name: /^Executar consulta/ }).click();
  await expect(page.getByRole('cell', { name: '4.999', exact: true })).toBeVisible();
  expect(reads.some(p => p.endsWith('.parquet'))).toBe(true);
  const csvDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ CSV', exact: true }).click();
  const csv = await csvDownload;
  expect(await readFile((await csv.path())!, 'utf8')).toContain('4999');
  const parquetDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ Parquet', exact: true }).click();
  const parquet = await parquetDownload;
  expect((await readFile((await parquet.path())!)).subarray(0, 4).toString()).toBe('PAR1');
  await page.getByLabel('Consulta SQL').fill('SELECT * FROM lake.main.inline_table');
  await page.getByRole('button', { name: /^Executar consulta/ }).click();
  await expect(page.getByRole('cell', { name: '42', exact: true })).toBeVisible();
  await page.getByLabel('Consulta SQL').fill('SELECT count(*) AS total FROM lake.main.despesas d CROSS JOIN lake.main.inline_table i');
  await page.getByRole('button', { name: /^Executar consulta/ }).click();
  await expect(page.getByRole('cell', { name: '4.999', exact: true })).toBeVisible();
  expect(scopes.at(-1)).toEqual(['main.despesas', 'main.inline_table']);
  await page.getByLabel('Consulta SQL').fill('SELECT SUM(sin(i)) FROM range(1000000000) t(i)');
  await page.getByRole('button', { name: /^Executar consulta/ }).click();
  await page.getByRole('button', { name: 'Cancelar consulta' }).click();
  await expect(page.getByRole('button', { name: /^Executar consulta/ })).toBeEnabled({ timeout: 10000 });
  await page.getByRole('tab', { name: 'Gráfico', exact: true }).click();
  await expect(page.locator('.chart-shell canvas')).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/explorer.png', fullPage: true });
  await page.getByLabel('Área do catálogo').selectOption('metadata');
  await expect(page.getByRole('button', { name: /Histórico dos metadados/ })).toBeVisible();
});
